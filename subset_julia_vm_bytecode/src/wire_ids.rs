impl serde::Serialize for crate::builtins::BuiltinId {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        s.serialize_u32(builtinid_to_wire_id(*self))
    }
}

impl<'de> serde::Deserialize<'de> for crate::builtins::BuiltinId {
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        let id = u32::deserialize(d)?;
        builtinid_from_wire_id(id)
            .ok_or_else(|| serde::de::Error::custom(format!("unknown BuiltinId wire ID: {id}")))
    }
}

impl serde::Serialize for crate::intrinsics::Intrinsic {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        s.serialize_u32(intrinsic_to_wire_id(*self))
    }
}

impl<'de> serde::Deserialize<'de> for crate::intrinsics::Intrinsic {
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        let id = u32::deserialize(d)?;
        intrinsic_from_wire_id(id)
            .ok_or_else(|| serde::de::Error::custom(format!("unknown Intrinsic wire ID: {id}")))
    }
}
