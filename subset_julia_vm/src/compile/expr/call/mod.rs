fn is_range_bridge_value_type(ty: &ValueType) -> bool {
    is_integer_value_type(ty) || matches!(ty, ValueType::F16 | ValueType::F32 | ValueType::F64)
}

fn is_array_like_julia_type(ty: &JuliaType) -> bool {
    match ty {
        JuliaType::Array
        | JuliaType::VectorOf(_)
        | JuliaType::MatrixOf(_)
        | JuliaType::AbstractArray => true,
        JuliaType::Struct(name) => {
            name == "Array"
                || name == "Vector"
                || name == "Matrix"
                || name.starts_with("Array{")
                || name.starts_with("Vector{")
                || name.starts_with("Matrix{")
        }
        _ => false,
    }
}

fn julia_struct_base_name(name: &str) -> &str {
    let base_name = name.split('{').next().unwrap_or(name);
    base_name.rsplit('.').next().unwrap_or(base_name)
}

