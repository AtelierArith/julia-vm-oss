/// CoreType-native port of the legacy
/// `is_abstract_array_family_type_name(&ty.to_string())` parameter probe
/// (Issue #6495, stage 7a). Image analysis vs the legacy rendered-name check:
///
/// - `JuliaType::AbstractArray` images as `Abstract(AbstractArray)`; the
///   bare-name `Struct` spellings `"AbstractVector"`/`"AbstractMatrix"`/
///   `"DenseArray"` image as their dedicated `CoreAbstract` variants, and
///   `"DenseVector"`/`"DenseMatrix"` (no dedicated variant) as `Named` — all
///   render the same family base name the legacy check matched.
/// - Parametric spellings (`AbstractArray{T,N}` etc.) image as `Struct` with
///   the family name (module + params already stripped by the bridge); the
///   legacy check stripped both from the rendering, mirrored here via
///   `is_abstract_array_family_type_name`'s own base-name strip for
///   module-qualified `Named` images.
/// - `UnionAll` recurses into the body like the legacy rendering
///   (`"AbstractArray{T} where T"` splits at `'{'` to the family name).
///   Accepted divergence (gate + suite referee, zero hits): a *bare*-body
///   `UnionAll` (`"AbstractVector where T"`, an unused `where` variable)
///   renders with no `'{'`, so the legacy check rejected it; the structural
///   recursion accepts it — unreachable from lowering.
/// - `TypeVar` images render as their variable name (never a family name):
///   rejected on both sides.
pub(in crate::compile) fn core_is_abstract_array_family_type(core: &CoreType) -> bool {
    match core {
        CoreType::Abstract(
            CoreAbstract::AbstractArray
            | CoreAbstract::AbstractVector
            | CoreAbstract::AbstractMatrix
            | CoreAbstract::DenseArray,
        ) => true,
        CoreType::Struct { name, .. }
        | CoreType::Named(name)
        | CoreType::AbstractUser { name, .. } => is_abstract_array_family_type_name(name),
        CoreType::UnionAll { body, .. } => core_is_abstract_array_family_type(body),
        _ => false,
    }
}

fn is_rank_unknown_array_julia_type(ty: &JuliaType) -> bool {
    match ty {
        JuliaType::Array => true,
        // The bare, element-free array-family aliases (`Array`/`Vector`/`Matrix`)
        // are produced by `infer_julia_type` for an array value whose element
        // type is unknown at compile time — most notably a comprehension
        // (`[expr for ...]`), which images as `JuliaType::Struct("Vector")`
        // (Issue #7266). Element-specific methods (`::AbstractVector{<:Real}`,
        // `::Vector{Int64}`) must fall to runtime dispatch on the concrete value
        // instead of mis-matching statically.
        JuliaType::Struct(name) => {
            matches!(julia_struct_base_name(name), "Array" | "Vector" | "Matrix")
        }
        _ => false,
    }
}

fn is_public_dict_constructor_method_call(function: &str, args: &[Expr]) -> bool {
    if function == "Dict" {
        return true;
    }
    if !function.starts_with("Dict{") {
        return false;
    }
    args.is_empty() || args.len() == 1 || args.iter().all(|a| matches!(a, Expr::Pair { .. }))
}

/// Bare public `Set(...)` construction routes through the pure-Julia `Set`
/// constructor methods (`Set()`, `Set(itr)`) via ordinary method dispatch
/// (Issue #6721), mirroring `is_public_dict_constructor_method_call`. The
/// parametric `Set{T}(...)` forms are handled separately by
/// `try_compile_explicit_public_set_constructor` (analogous to the Dict
/// `_dict_from_explicit_types` route) because the element type must be lifted
/// from the `{T}` type argument into a runtime type value.
fn is_public_set_constructor_method_call(function: &str, args: &[Expr]) -> bool {
    let _ = args;
    function == "Set"
}

/// Extract the single `{T}` element-type argument for an explicit
/// `Set{T}()` / `Set{T}(itr)` public construction call (Issue #6721).
fn explicit_public_set_type_arg(function: &str, args: &[Expr]) -> Option<TypeExpr> {
    if !function.starts_with("Set{") {
        return None;
    }
    if args.len() > 1 {
        return None;
    }
    let (base, type_args) = parse_parametric_call(function)?;
    (base == "Set" && type_args.len() == 1).then(|| type_args.into_iter().next())?
}

fn explicit_public_dict_type_args(function: &str, args: &[Expr]) -> Option<Vec<TypeExpr>> {
    if !is_public_dict_constructor_method_call(function, args) {
        return None;
    }
    let (base, type_args) = parse_parametric_call(function)?;
    (base == "Dict" && type_args.len() == 2).then_some(type_args)
}

fn is_dict_like_julia_type(ty: &JuliaType) -> bool {
    matches!(ty, JuliaType::Dict)
        || matches!(ty, JuliaType::Struct(name) if name.split('{').next() == Some("Dict"))
}

/// A `Set` value is now a pure-Julia struct over `Dict{T,Nothing}` (Issue
/// #6721). This recognizes both the legacy native `JuliaType::Set` carrier and
/// the `Struct("Set{...}")` form so membership / mutation routing can keep
/// `Set` operations on method dispatch rather than the native builtins.
fn is_set_like_julia_type(ty: &JuliaType) -> bool {
    matches!(ty, JuliaType::Set)
        || matches!(ty, JuliaType::Struct(name) if name.split('{').next() == Some("Set"))
}

