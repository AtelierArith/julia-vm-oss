    /// Issue #6657: route a `getindex` whose receiver type is unknown at
    /// compile time (statically `Any`) to a user-defined `getindex` /
    /// `Base.getindex` override when one exists, falling back to native
    /// indexing otherwise.
    ///
    /// The common case — no user `getindex` override, or a statically-typed
    /// receiver — returns `None`, so the caller keeps the fast `IndexLoad`
    /// path untouched. Only when (a) the receiver is statically `Any`, (b) the
    /// index is scalar (not a slice/range/array index), and (c) the user has
    /// defined `getindex` candidate methods, does this emit a
    /// `CallTypedDispatchOrBuiltin(GetIndex, ..)`: at runtime it dispatches to
    /// a matching user override, or runs the native-indexing builtin fallback
    /// when none matches (mirroring `push!` / `haskey` etc.).
    pub(in crate::compile) fn try_compile_dynamic_getindex_dispatch(
        &mut self,
        args: &[Expr],
    ) -> Option<CResult<ValueType>> {
        // Need a collection plus at least one index.
        if args.len() < 2 {
            return None;
        }
        // Only when the receiver type is unknown at compile time: a concrete
        // receiver already resolves to the correct fast path or a
        // compile-time-proven dispatch (`has_user_dispatch_method_for_arg_types`).
        if !matches!(self.infer_expr_type(&args[0]), ValueType::Any) {
            return None;
        }
        // Restrict to a genuinely dynamic receiver. A `Var` receiver must be an
        // `Any`-typed parameter (`fg(xs) = xs[1]`): a typed parameter — including a
        // Base `getindex(a::Array{T,N}, ...)` body whose parametric param erases to
        // `ValueType::Any` — keeps native indexing, so this does not add dispatch
        // overhead inside Base methods or alter their semantics (#6657). The typed
        // override case is already handled earlier by
        // `has_user_dispatch_method_for_arg_types`.
        if let Expr::Var(name, _) = &args[0] {
            if !self.any_params.contains(name) {
                return None;
            }
        }
        // Slice/range/array indices have their own builtin fast paths and are
        // outside the scalar-override gap; leave them on the existing route.
        let has_slice_like_index = args[1..].iter().any(|idx| {
            matches!(idx, Expr::Range { .. } | Expr::SliceAll { .. })
                || is_array_like_julia_type(&self.infer_julia_type(idx))
                || matches!(
                    self.infer_expr_type(idx),
                    ValueType::Array
                        | ValueType::ArrayOf(_, _)
                        | ValueType::Bool
                        | ValueType::Range
                        | ValueType::Rng
                )
        });
        if has_slice_like_index {
            return None;
        }
        // Only *user-defined* (non-Base) `getindex` overrides count: Base
        // `getindex` is pure Julia (so it has IR and would otherwise pass the
        // `function_ir_by_global_index` filter), but native indexing already
        // handles those via the `IndexLoad` builtin fallback. Requiring a user
        // override keeps the common no-override program on the native fast path
        // (empty candidates → `None`) — and avoids routing every `f(xs)=xs[1]`
        // through dynamic dispatch (Issue #6657).
        let candidates =
            self.user_override_candidates_for_names(&["getindex", "Base.getindex"], args.len());
        if candidates.is_empty() {
            return None;
        }
        for arg in args {
            if let Err(e) = self.compile_expr(arg) {
                return Some(Err(e));
            }
        }
        self.emit(Instr::CallTypedDispatchOrBuiltin(
            BuiltinId::GetIndex,
            "getindex".to_string(),
            args.len(),
            candidates,
        ));
        Some(Ok(ValueType::Any))
    }

    /// Single-parameter user method candidates for `CallDynamicOrBuiltin`
    /// (Issue #6496: index-only payload; the runtime derives the expected
    /// first-parameter type name from `FunctionInfo`).
    fn user_unary_runtime_candidates(
        &self,
        table: &crate::compile::method_table::MethodTable,
    ) -> Vec<usize> {
        table
            .methods
            .iter()
            .filter(|m| {
                m.param_count() == 1
                    && self
                        .shared_ctx
                        .function_ir_by_global_index
                        .contains_key(&m.global_index)
            })
            .filter_map(|m| (m.param_specificity(0) > 0).then_some(m.global_index))
            .collect()
    }

    /// Candidate function indices for the `CallTypedDispatch[OrBuiltin*]`
    /// family (Issue #6496: index-only payloads; the runtime derives each
    /// candidate's per-arity expected type names from `FunctionInfo`).
    /// `MethodSig::accepts_arity` replaces the historical
    /// `runtime_type_names_for_arity(..).is_some()` arity gate.
    pub(in crate::compile) fn user_runtime_candidates_for_names(
        &self,
        names: &[&str],
        arity: usize,
    ) -> Vec<usize> {
        let mut candidates = Vec::new();
        for name in names {
            if let Some(table) = self.method_tables.get(*name) {
                for method in table.methods.iter() {
                    if !self
                        .shared_ctx
                        .function_ir_by_global_index
                        .contains_key(&method.global_index)
                    {
                        continue;
                    }
                    if candidates.contains(&method.global_index) {
                        continue;
                    }
                    if method.accepts_arity(arity) {
                        candidates.push(method.global_index);
                    }
                }
            }
        }
        candidates
    }

    /// Like [`Self::user_runtime_candidates_for_names`], but restricted to
    /// *user-defined* (non-Base) overrides. A function whose Base methods are
    /// pure Julia (e.g. `getindex`) would otherwise pass the
    /// `function_ir_by_global_index` filter even with no user override; this
    /// excludes Base-origin methods via the method table's `base_function_count`
    /// (Issue #6657).
    pub(in crate::compile) fn user_override_candidates_for_names(
        &self,
        names: &[&str],
        arity: usize,
    ) -> Vec<usize> {
        let mut candidates = Vec::new();
        for name in names {
            if let Some(table) = self.method_tables.get(*name) {
                for method in table.methods.iter() {
                    if table.is_base_program_global_index(method.global_index) {
                        continue;
                    }
                    // A free-typevar array signature (`Array{T,N}`) is the Base
                    // array `getindex` shape, never a concrete user override.
                    // Exclude it so Base array `getindex` is not treated as a
                    // user candidate even when origin classification is
                    // unavailable (e.g. a double-merged program) — which would
                    // otherwise route `a[i]` inside Base bodies through dynamic
                    // dispatch and recurse (Issue #6657).
                    if method.param_matches_at(
                        0,
                        crate::compile::method_table::core_type_is_free_typevar_array,
                    ) {
                        continue;
                    }
                    if !self
                        .shared_ctx
                        .function_ir_by_global_index
                        .contains_key(&method.global_index)
                    {
                        continue;
                    }
                    if candidates.contains(&method.global_index) {
                        continue;
                    }
                    if method.accepts_arity(arity) {
                        candidates.push(method.global_index);
                    }
                }
            }
        }
        candidates
    }

