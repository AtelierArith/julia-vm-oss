//! Function call compilation.
//!
//! Handles compilation of:
//! - User-defined function calls with multiple dispatch
//! - Module-qualified calls (Module.func)
//! - Dynamic type constructor calls
//! - N-ary operator reduction
//!
//! # Callable Variable Dispatch Heuristics
//!
//! When a variable name is used as a function (e.g., `f(x, y)`), the compiler must
//! determine how to dispatch the call. This decision is made at compile-time based
//! on the variable's static type:
//!
//! | Variable Type      | Dispatch Method                    | Use Case                           |
//! |--------------------|------------------------------------|------------------------------------|
//! | `ValueType::DataType` | `compile_function_variable_call`| `T = Float64; T(1)`                |
//! | `ValueType::Function` | `compile_function_variable_call`| `f::Function; f(x)`                |
//! | `ValueType::GlobalRef`| `compile_globalref_call`        | `ref = GlobalRef(...); ref(x)`     |
//! | `ValueType::Any`      | `compile_function_variable_call`| Untyped function parameters        |
//!
//! ## `ValueType::Any` Runtime Dispatch
//!
//! For untyped function parameters (type `Any`), the compiler emits
//! `CallFunctionVariable` and lets the VM resolve callability from the runtime value:
//! DataType constructors/converters, Function, Closure, and callable struct instances.
//!
//! - **`__field_func_` prefix**: Always use `compile_function_variable_call`
//!   - Generated by lowering for `obj.method(args)` patterns
//!
//! ## Runtime Notes
//!
//! - Primitive `DataType` one-argument calls are still handled as conversions.
//! - Struct `DataType` calls can fall back to the default field constructor when
//!   there is no compiled constructor method.
//!
//! This keeps constructor-vs-function selection out of compile-time arity heuristics
//! and aligns with Julia's runtime callable model (Issue #3895).

