fn canonical_operator_callable_name(name: &str) -> &str {
    match name {
        // Macro expansion can reify Unicode comparisons as callable heads.
        // Source binary expressions already lower through BinaryOp; normalize
        // callable spellings here so expanded forms share the same dispatch path
        // (Issue #8326).
        "≤" => "<=",
        "≥" => ">=",
        "≠" => "!=",
        _ => name,
    }
}

fn is_typemax_uint64_call(expr: &Expr) -> bool {
    matches!(
        expr,
        Expr::Call {
            function,
            args,
            kwargs,
            ..
        } if function == "typemax"
            && kwargs.is_empty()
            && matches!(args.as_slice(), [Expr::Var(name, _)] if name == "UInt64")
    )
}

